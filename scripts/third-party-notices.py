#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md: the licences of everything shipped.

Covers the Rust crates in the desktop app and the `nuxd` CLI (normal
dependencies only, on every release target, via `cargo about`) and the
JavaScript packages bundled into the UI (`pnpm licenses list --prod`).
Each distinct licence text appears once, with the packages that use it.
The UnRAR library compiled into `unrar_sys` is listed separately: the
crate declares MIT/Apache for its Rust code, but the C++ source it builds
is under UnRAR's own licence, which `cargo about` can't see.
The app shows the file under Settings → About.

Needs `cargo about` (`cargo install cargo-about --locked --features cli`)
and pnpm. Run from the repository root; rerun when dependencies change.
"""

import json
import subprocess
from collections import defaultdict
from pathlib import Path

LICENCE_FILES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "license.md")


def rust() -> dict[tuple[str, str], set[str]]:
    groups: dict[tuple[str, str], set[str]] = defaultdict(set)
    for manifest in ("src-tauri/Cargo.toml", "cli/Cargo.toml"):
        out = subprocess.run(
            ["cargo", "about", "generate", "--format", "json", "-c", "about.toml", "-m", manifest],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
        for licence in json.loads(out)["licenses"]:
            key = (licence["name"], licence["text"].strip())
            for user in licence["used_by"]:
                crate = user["crate"]
                if crate["name"].startswith("nuxd"):
                    continue  # our own crates
                groups[key].add(f'{crate["name"]} {crate["version"]}')
    return groups


def unrar() -> dict[tuple[str, str], set[str]]:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    packages = [p for p in json.loads(out)["packages"] if p["name"] == "unrar_sys"]
    if len(packages) != 1:
        raise SystemExit(f"expected one unrar_sys in the dependency graph, found {len(packages)}")
    package = packages[0]
    licence = Path(package["manifest_path"]).parent / "vendor" / "unrar" / "license.txt"
    text = licence.read_text(errors="replace").strip("\n").rstrip()
    if "UnRAR source code may be used" not in text:
        raise SystemExit(f"{licence} is not the UnRAR licence we reviewed")
    return {("UnRAR licence (freeware)", text): {f'UnRAR library, in unrar_sys {package["version"]}'}}


def javascript() -> dict[tuple[str, str], set[str]]:
    out = subprocess.run(
        ["pnpm", "--dir", "ui", "licenses", "list", "--prod", "--json"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    groups: dict[tuple[str, str], set[str]] = defaultdict(set)
    for licence, packages in json.loads(out).items():
        for package in packages:
            text = ""
            for path in package.get("paths", []):
                for name in LICENCE_FILES:
                    candidate = Path(path) / name
                    if candidate.is_file():
                        text = candidate.read_text(errors="replace").strip()
                        break
                if text:
                    break
            key = (licence, text or f"Licensed under {licence}.")
            for version in package.get("versions", []):
                groups[key].add(f'{package["name"]} {version}')
    return groups


def render(title: str, groups: dict[tuple[str, str], set[str]]) -> list[str]:
    lines = [f"## {title}", ""]
    for (name, text), users in sorted(groups.items(), key=lambda item: (item[0][0], sorted(item[1]))):
        lines += [f"### {name}", "", "Used by: " + ", ".join(sorted(users)), "", "```text", text, "```", ""]
    return lines


def main() -> None:
    lines = [
        "# Third-party notices",
        "",
        "Nux Downloader is built from the projects below, all open source",
        "except the UnRAR library (freeware, used for RAR extraction). Each",
        "is used under the licence shown, and the full text of every licence",
        "follows. Generated by `scripts/third-party-notices.py`.",
        "",
    ]
    lines += render("Rust crates (the app and the nuxd command)", rust())
    lines += render("UnRAR (RAR extraction)", unrar())
    lines += render("JavaScript packages (the app's interface)", javascript())
    Path("THIRD_PARTY_NOTICES.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
